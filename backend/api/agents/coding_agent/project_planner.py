class ProjectPlanner:
    """Generate a full project blueprint using an LLM."""

    # ── Public entry point ─────────────────────────────────────────────────────

    async def plan(self, goal: str, stack: str, design_brief: str | None = None) -> dict[str, Any]:
        """Return a project blueprint dict.

        Schema::

            {
              "name": "clothing-website",
              "description": "...",
              "files": [{"path": "src/App.tsx", "content": "..."}],
              "dependencies": ["react", "react-dom"],
              "dev_dependencies": ["vite", "@vitejs/plugin-react", "tailwindcss", ...],
              "scripts": {"dev": "vite", "build": "vite build", "preview": "vite preview"},
              "commands_after_install": ["npx tailwindcss init -p"]
            }

        *design_brief* — optional design intelligence string from DesignResearcher.
        When provided it is injected into the code-generation prompt so the
        generated UI follows current design trends for the project category.
        """
        if stack == "vite-react-tailwind":
            return await self._plan_vite_react(goal, design_brief=design_brief)
        if stack == "nextjs":
            return await self._plan_nextjs(goal, design_brief=design_brief)
        if stack == "python-flask":
            return await self._plan_flask(goal)
        if stack == "html-vanilla":
            return await self._plan_vanilla(goal)
        # Default fallback
        return await self._plan_vite_react(goal, design_brief=design_brief)

    # ── Stack-specific planners ────────────────────────────────────────────────

    async def _plan_vite_react(self, goal: str, design_brief: str | None = None) -> dict[str, Any]:
        """Generate a Vite + React + Tailwind project."""
        project_name = self._slugify(goal)
        app_tsx = await self._generate_app_tsx(goal, "vite-react-tailwind", design_brief=design_brief)

        base_plan: dict[str, Any] = {
            "name": project_name,
            "description": goal,
            "dependencies": ["react", "react-dom"],
            "dev_dependencies": [
                "vite",
                "@vitejs/plugin-react",
                "tailwindcss",
                "postcss",
                "autoprefixer",
                "typescript",
                "@types/react",
                "@types/react-dom",
            ],
            "scripts": {
                "dev": "vite",
                "build": "tsc && vite build",
                "preview": "vite preview",
                "lint": "tsc --noEmit",
            },
            "commands_after_install": [],
            "files": [
                {"path": "index.html", "content": _INDEX_HTML},
                {"path": "vite.config.ts", "content": _VITE_CONFIG},
                {"path": "tailwind.config.js", "content": _TAILWIND_CONFIG},
                {"path": "tsconfig.json", "content": _TSCONFIG},
                {"path": "tsconfig.node.json", "content": _TSCONFIG_NODE},
                {"path": "src/main.tsx", "content": _MAIN_TSX},
                {"path": "src/index.css", "content": _INDEX_CSS},
                {"path": "src/App.tsx", "content": app_tsx},
            ],
        }

        # Inject package.json
        base_plan["files"].append(
            {
                "path": "package.json",
                "content": self._make_package_json(
                    project_name,
                    base_plan["dependencies"],
                    base_plan["dev_dependencies"],
                    base_plan["scripts"],
                ),
            }
        )

        # PostCSS config for Tailwind v3 (v4 removed the direct PostCSS plugin)
        base_plan["files"].append(
            {
                "path": "postcss.config.js",
                "content": (
                    "export default {\n"
                    "  plugins: {\n"
                    "    tailwindcss: {},\n"
                    "    autoprefixer: {},\n"
                    "  },\n"
                    "};\n"
                ),
            }
        )

        return base_plan

