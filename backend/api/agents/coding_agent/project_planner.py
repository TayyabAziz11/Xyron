from __future__ import annotations

"""
ProjectPlanner — use an LLM to generate a complete project file tree.

The planner returns a structured dict that other modules (CodeGenerator,
DependencyInstaller, …) consume directly.  All heavy content (file bodies,
component JSX, etc.) is generated by the LLM; the planner only directs the
prompt and parses the response.
"""

import json
import logging
import re
import textwrap
from typing import Any

from api.services.openai_client import openai_client

logger = logging.getLogger(__name__)


def _strip_code_fences(text: str) -> str:
    """Remove markdown code fences that LLMs sometimes wrap output in."""
    text = text.strip()
    text = re.sub(r"^```[a-zA-Z]*\n?", "", text)
    text = re.sub(r"\n?```\s*$", "", text)
    return text.strip()


# Packages that are always installed in a vite-react-tailwind project
_SAFE_PACKAGES = frozenset({"react", "react-dom"})

def _validate_app_tsx(code: str, is_next: bool) -> str | None:
    """Validate LLM-generated App.tsx. Returns the code if valid, None to trigger fallback.

    Rejects:
    - Next.js imports in a Vite project
    - Any npm package imports other than react/react-dom (they're not installed)
    - Local relative imports other than ./components/* and ./data/*
    """
    if not code or len(code) < 50:
        return None

    # Reject if HTML `class=` attribute is used instead of JSX `className=`
    if re.search(r'\bclass\s*=\s*["\']', code):
        logger.warning("[PROJECT_PLANNER] rejected App.tsx: HTML class= attribute (use className=)")
        return None

    for line in code.splitlines():
        line = line.strip()
        if not line.startswith("import "):
            continue
        # Extract 'from "..."' or "from '...'"
        m = re.search(r"""from\s+['"]([^'"]+)['"]""", line)
        if not m:
            continue
        pkg = m.group(1)

        # Next.js check (Vite projects only)
        if not is_next and pkg.startswith("next/"):
            logger.warning("[PROJECT_PLANNER] rejected App.tsx: next/* import in Vite project")
            return None

        # Local relative imports: only allow ./components/* and ./data/*
        if pkg.startswith("./") or pkg.startswith("../"):
            allowed_local = ("./components/", "./data/")
            if not any(pkg.startswith(p) for p in allowed_local):
                logger.warning("[PROJECT_PLANNER] rejected App.tsx: disallowed local import %r", pkg)
                return None
            continue

        # npm package — only safe ones allowed
        root_pkg = pkg.split("/")[0]
        if root_pkg not in _SAFE_PACKAGES:
            logger.warning("[PROJECT_PLANNER] rejected App.tsx: uninstalled package %r", pkg)
            return None

    # Reject if the file has no h1 or h2 (visual reviewer requires them)
    if not re.search(r'<h[12][\s>]', code):
        logger.warning("[PROJECT_PLANNER] rejected App.tsx: no h1/h2 heading found")
        return None

    return code


