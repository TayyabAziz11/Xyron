    # ── Utilities ─────────────────────────────────────────────────────────────

    @staticmethod
    def _slugify(text: str) -> str:
        """Convert goal text to a safe project name."""
        cleaned = re.sub(
            r"^(build|create|make|generate|design|write|develop|set up|setup)(\s+me)?\s+(an?\s+)?",
            "",
            text.strip(),
            flags=re.IGNORECASE,
        )
        cleaned = cleaned.lower()
        cleaned = re.sub(r"[^a-z0-9]+", "-", cleaned)
        cleaned = re.sub(r"-{2,}", "-", cleaned).strip("-")
        return cleaned[:50] or "my-project"

    # Pin versions for packages where "latest" breaks the generated template.
    # tailwindcss v4 removed the direct PostCSS plugin — our template uses v3 syntax.
    _DEV_VERSION_PINS: dict[str, str] = {
        "tailwindcss":  "^3.4.0",
        "autoprefixer": "^10.4.0",
        "postcss":      "^8.4.0",
    }

    @staticmethod
    def _make_package_json(
        name: str,
        deps: list[str],
        dev_deps: list[str],
        scripts: dict[str, str],
    ) -> str:
        pkg = {
            "name": name,
            "version": "0.1.0",
            "private": True,
            "type": "module",
            "scripts": scripts,
            "dependencies": {d: "latest" for d in deps},
            "devDependencies": {
                d: ProjectPlanner._DEV_VERSION_PINS.get(d, "latest")
                for d in dev_deps
            },
        }
        return json.dumps(pkg, indent=2)
